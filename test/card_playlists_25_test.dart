// desktop#25: the last-sync line says how many playlists the sync wrote and
// how many of the card's own the server read, and, when some of their
// entries matched nothing, links to where those wait for review.

import 'dart:convert';
import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:http/http.dart' as http;
import 'package:http/testing.dart';
import 'package:trobar_desktop/app_prefs.dart';
import 'package:trobar_desktop/card_store.dart';
import 'package:trobar_desktop/l10n/gen/app_localizations.dart';
import 'package:trobar_desktop/main.dart';
import 'package:trobar_desktop/models.dart';

const _config = DeviceConfig(serverUrl: 'http://srv/', token: 't0k');

void main() {
  late Directory root;
  setUp(() async {
    root = Directory.systemTemp.createTempSync('trobar_playlists25');
    await AppPrefs.load(file: File('${root.path}/prefs.json'));
  });
  tearDown(() => root.deleteSync(recursive: true));

  Future<AppLocalizations> open(WidgetTester tester, SyncOutcome outcome,
      {void Function(Uri)? openUrl}) async {
    tester.view.physicalSize = const Size(1000, 1600);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.reset);
    await tester.runAsync(() async {
      await writeSyncOutcome(root, outcome);
      await tester.pumpWidget(MaterialApp(
        localizationsDelegates: AppLocalizations.localizationsDelegates,
        supportedLocales: AppLocalizations.supportedLocales,
        home: CardScreen(
            root: root,
            config: _config,
            client: MockClient((_) async => http.Response('{"name": "Card"}', 200)),
            openUrl: openUrl),
      ));
      await Future<void>.delayed(const Duration(milliseconds: 300));
    });
    await tester.pump();
    return AppLocalizations.of(tester.element(find.byType(CardScreen)));
  }

  testWidgets('the playlists line, and the unknown entries with a link to them',
      (tester) async {
    final opened = <Uri>[];
    final l = await open(
        tester,
        SyncOutcome(syncedAt: DateTime.now(), playlists: 3, devicePlaylists: 2, unknownEntries: 4),
        openUrl: opened.add);
    expect(find.text('${l.syncPlaylists(3, 2)} ${l.syncUnknownEntries(4)}'), findsOneWidget);
    await tester.tap(find.text(l.reviewUnknownEntries));
    expect(opened, [Uri.parse('http://srv/#/devices')]);
  });

  testWidgets('everything understood: the line, and no link', (tester) async {
    final l = await open(
        tester, SyncOutcome(syncedAt: DateTime.now(), playlists: 1, devicePlaylists: 1));
    expect(find.text(l.syncPlaylists(1, 1)), findsOneWidget);
    expect(find.text(l.reviewUnknownEntries), findsNothing);
  });

  testWidgets('no playlists either way: no line', (tester) async {
    final l = await open(tester, SyncOutcome(syncedAt: DateTime.now(), downloaded: 2));
    expect(find.textContaining(l.syncPlaylists(0, 0)), findsNothing);
    expect(find.text(l.syncSummary(2, 0)), findsOneWidget);
  });
  testWidgets('a sync keeps its playlist counts on the card', (tester) async {
    final client = MockClient((req) async {
      if (req.url.path == '/api/device/info') return http.Response('{"name": "Card"}', 200);
      if (req.url.path == '/api/device/changes') {
        return http.Response(jsonEncode({'to_download': [], 'to_delete': [], 'downloaded': [],
          'playlists': [
          {'name': 'Mix', 'filename': 'Mix.m3u8', 'content': '#EXTM3U\n# Generated by Trobar\nA/B/01 - T.mp3\n'},
          {'name': 'Run', 'filename': 'Run.m3u8', 'content': '#EXTM3U\n# Generated by Trobar\nA/B/01 - T.mp3\n'},
          {'name': 'Walk', 'filename': 'Walk.m3u8', 'content': '#EXTM3U\n# Generated by Trobar\nA/B/01 - T.mp3\n'}]}), 200);
      }
      if (req.url.path == '/api/device/playlists') {
        return http.Response('{"playlists": 1, "tracks": 3, "matched": 1, "unknown": 2}', 200);
      }
      return http.Response('{"status": "ok"}', 200);
    });
    tester.view.physicalSize = const Size(1000, 1600);
    tester.view.devicePixelRatio = 1;
    addTearDown(tester.view.reset);
    await tester.runAsync(() async {
      await File('${root.path}/Mine.m3u8').writeAsString('A/B/01 - T.mp3\nNobody/None/01 - X.mp3\n');
      await tester.pumpWidget(MaterialApp(
        localizationsDelegates: AppLocalizations.localizationsDelegates,
        supportedLocales: AppLocalizations.supportedLocales,
        home: CardScreen(root: root, config: _config, client: client),
      ));
      await Future<void>.delayed(const Duration(milliseconds: 300));
      await tester.tap(find.byIcon(Icons.sync));
      await Future<void>.delayed(const Duration(milliseconds: 500));
    });
    await tester.pump();
    final kept = (await tester.runAsync(() => readSyncOutcome(root)))!;
    // Three different numbers, so none can stand in for another.
    expect([kept.playlists, kept.devicePlaylists, kept.unknownEntries], [3, 1, 2]);
    await tester.pumpWidget(const SizedBox());
    await tester.pump(const Duration(minutes: 2));
  });
}
